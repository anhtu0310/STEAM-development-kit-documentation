#!/usr/bin/env python3
"""Generate main/font8x16.h: an 8x16 bitmap font (ASCII 32..126).

Rendered once from DejaVu Sans Mono Bold (Bitstream Vera licence, free to
embed). Each glyph is 16 bytes, one per row, bit 7 = leftmost pixel.
Usage: python3 tools/gen_font.py /usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf
"""
import sys
from PIL import Image, ImageDraw, ImageFont

path = sys.argv[1] if len(sys.argv) > 1 else \
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
font = ImageFont.truetype(path, 15)
ascent, _ = font.getmetrics()
rows = []
for code in range(32, 127):
    image = Image.new("L", (8, 16), 0)
    ImageDraw.Draw(image).text((0, 13 - ascent), chr(code), fill=255, font=font)
    glyph = []
    for y in range(16):
        bits = 0
        for x in range(8):
            if image.getpixel((x, y)) >= 110:
                bits |= 0x80 >> x
        glyph.append(bits)
    rows.append((code, glyph))

out = ["#pragma once", "// Generated by tools/gen_font.py from DejaVu Sans Mono Bold.",
       "// 95 glyphs (ASCII 32..126), 16 rows each, bit 7 = leftmost pixel.",
       "#include <cstdint>", "", "namespace font8x16 {",
       "inline constexpr int WIDTH = 8;", "inline constexpr int HEIGHT = 16;",
       "inline constexpr uint8_t GLYPHS[95][16] = {"]
for code, glyph in rows:
    c = chr(code)
    label = {"\\": "backslash", "'": "quote"}.get(c, c)
    out.append("    {" + ",".join(f"0x{b:02X}" for b in glyph) + "},  // " + label)
out += ["};", "", "inline const uint8_t *glyph(char c) {",
        "    const unsigned index = static_cast<unsigned char>(c);",
        "    return GLYPHS[(index >= 32 && index <= 126) ? index - 32 : '?' - 32];",
        "}", "}  // namespace font8x16", ""]
open("main/font8x16.h", "w").write("\n".join(out))
